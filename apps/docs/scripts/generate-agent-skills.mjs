#!/usr/bin/env node
/**
 * Sync Agent Skills from the monorepo `.cursor/skills/` into a Workers-safe
 * generated module, and emit `/.well-known/agent-skills/index.json` metadata
 * (digests of the exact artifact bytes that routes will serve).
 *
 * Runs on postinstall / before build - Workers have no filesystem at runtime.
 */

import { createHash } from "node:crypto";
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const DISCOVERY_SCHEMA = "https://schemas.agentskills.io/discovery/0.2.0/schema.json";
const NAME_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

const docsRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const skillsRoot = join(docsRoot, "../../.cursor/skills");
const outDir = join(docsRoot, "lib/generated");
const outFile = join(outDir, "agent-skills-data.ts");

/**
 * Minimal frontmatter parser for our SKILL.md files (name + description).
 * Supports plain scalars and YAML `>` / `>-` / `|` / `|-` blocks.
 * @param {string} content
 */
function parseFrontmatter(content) {
  const match = content.match(/^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/);
  if (!match) {
    throw new Error("SKILL.md missing YAML frontmatter");
  }

  const lines = match[1].split(/\r?\n/);
  /** @type {Record<string, string>} */
  const fields = {};

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const keyMatch = line.match(/^([a-zA-Z0-9_-]+):\s*(.*)$/);
    if (!keyMatch) continue;

    const key = keyMatch[1];
    const rest = keyMatch[2];
    const blockMatch = rest.match(/^([>|][-+]?)\s*$/);

    if (blockMatch) {
      const style = blockMatch[1];
      const blockLines = [];
      i += 1;
      while (i < lines.length) {
        const blockLine = lines[i];
        if (blockLine === "" || /^\s/.test(blockLine)) {
          blockLines.push(blockLine.replace(/^\s{2}/, ""));
          i += 1;
          continue;
        }
        i -= 1;
        break;
      }

      if (style.startsWith("|")) {
        fields[key] = blockLines.join("\n").trim();
      } else {
        fields[key] = blockLines
          .map((entry) => entry.trim())
          .filter(Boolean)
          .join(" ")
          .trim();
      }
      continue;
    }

    fields[key] = rest.trim().replace(/^["']|["']$/g, "");
  }

  const name = fields.name;
  const description = fields.description;

  if (!name) {
    throw new Error("SKILL.md frontmatter missing name");
  }
  if (!description) {
    throw new Error("SKILL.md frontmatter missing description");
  }
  if (description.length > 1024) {
    throw new Error(`SKILL.md description exceeds 1024 characters (${description.length})`);
  }

  return { name, description };
}

function listSkillDirs() {
  if (!existsSync(skillsRoot)) {
    throw new Error(`Skills directory not found: ${skillsRoot}`);
  }

  return readdirSync(skillsRoot)
    .filter((entry) => {
      const full = join(skillsRoot, entry);
      return statSync(full).isDirectory() && existsSync(join(full, "SKILL.md"));
    })
    .sort();
}

function main() {
  const skills = [];

  for (const dirName of listSkillDirs()) {
    if (!NAME_RE.test(dirName)) {
      throw new Error(`Invalid skill directory name: ${dirName}`);
    }

    const skillPath = join(skillsRoot, dirName, "SKILL.md");
    const bytes = readFileSync(skillPath);
    const text = bytes.toString("utf8");
    const { name, description } = parseFrontmatter(text);

    if (name !== dirName) {
      throw new Error(
        `Skill name mismatch: directory "${dirName}" vs frontmatter name "${name}"`,
      );
    }

    const digest = `sha256:${createHash("sha256").update(bytes).digest("hex")}`;
    skills.push({
      name,
      type: "skill-md",
      description,
      url: `/.well-known/agent-skills/${name}/SKILL.md`,
      digest,
      bodyBase64: bytes.toString("base64"),
    });
  }

  if (skills.length === 0) {
    throw new Error("No Agent Skills found to publish");
  }

  const index = {
    $schema: DISCOVERY_SCHEMA,
    skills: skills.map(({ name, type, description, url, digest }) => ({
      name,
      type,
      description,
      url,
      digest,
    })),
  };

  const fileBody = `/* eslint-disable */
// Auto-generated by scripts/generate-agent-skills.mjs - do not edit.
export const DISCOVERY_SCHEMA = ${JSON.stringify(DISCOVERY_SCHEMA)} as const;

export type AgentSkillArtifact = {
  name: string;
  type: "skill-md";
  description: string;
  url: string;
  digest: \`sha256:\${string}\`;
  bodyBase64: string;
};

export const agentSkillsIndex = ${JSON.stringify(index, null, 2)} as const;

export const agentSkillArtifacts: Record<string, AgentSkillArtifact> = ${JSON.stringify(
    Object.fromEntries(
      skills.map((skill) => [
        skill.name,
        {
          name: skill.name,
          type: skill.type,
          description: skill.description,
          url: skill.url,
          digest: skill.digest,
          bodyBase64: skill.bodyBase64,
        },
      ]),
    ),
    null,
    2,
  )} as const;
`;

  mkdirSync(outDir, { recursive: true });
  writeFileSync(outFile, fileBody);
}

main();
